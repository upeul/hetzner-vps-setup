#!/usr/bin/env bash
# Renderiza uma política por UID sem alterar outras tabelas nftables.
# Uso: render-egress-nftables.sh CONFIG OUT [observe|enforce] [USERS_FILE] [--apply]
# USERS_FILE contém um nome de conta por linha. Sem --apply apenas valida e grava.
set -euo pipefail

CONFIG="${1:?config yaml}"
OUT="${2:?output nft file}"
MODE="${3:-observe}"
USERS="${4:-/etc/devvps/egress-users}"
ACTION="${5:-}"
if [[ "$#" -gt 5 || ( -n "$ACTION" && "$ACTION" != --apply ) ]]; then
  echo 'Uso: render-egress-nftables.sh CONFIG OUT [observe|enforce] [USERS_FILE] [--apply]' >&2
  exit 2
fi

# Serializa deploy, inicialização e atualização DNS usando o mesmo lock.
exec 9>/run/lock/devvps-egress.lock
flock -x 9
python3 - "$CONFIG" "$OUT" "$MODE" "$USERS" "$ACTION" <<'PY'
import ipaddress
import os
import pwd
import socket
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

config_path, out_path = map(Path, sys.argv[1:3])
mode, users_path, action = sys.argv[3:]
if mode not in ("observe", "enforce"):
    raise SystemExit("egress_mode deve ser observe ou enforce")
data = yaml.safe_load(config_path.read_text())
policy = data["policy"]
if policy["default_outbound"] != "deny" or policy["allow_established_related"] is not True:
    raise SystemExit("A política requer default_outbound: deny e allow_established_related: true")

names = Path(users_path).read_text().splitlines()
if not names or any(not name.strip() or name != name.strip() for name in names):
    raise SystemExit("A lista de contas deve conter um nome por linha e não pode estar vazia")
uids = sorted({pwd.getpwnam(name).pw_uid for name in names})
if 0 in uids:
    raise SystemExit("A política de agentes não pode incluir root")

networks = {4: [], 6: []}
for cidr in data.get("static_cidrs", []) or []:
    net = ipaddress.ip_network(cidr, strict=False)
    networks[net.version].append(net)

# DNS externo pode ficar indisponível. Um destino sem resposta não ganha permissão;
# o timer tenta novamente. Isto não valida Host/SNI nem isola CDNs compartilhadas.
for domain in data["domains"]:
    addresses = set()
    try:
        answers = socket.getaddrinfo(domain, 443, type=socket.SOCK_STREAM)
    except socket.gaierror as error:
        print(f"WARN DNS {domain}: {error}; destino omitido até próxima atualização", file=sys.stderr)
        continue
    for family, _, _, _, sockaddr in answers:
        if family in (socket.AF_INET, socket.AF_INET6):
            addresses.add(ipaddress.ip_address(sockaddr[0]))
    if not addresses:
        print(f"WARN DNS {domain}: sem endereços IPv4/IPv6; destino omitido", file=sys.stderr)
    for address in addresses:
        networks[address.version].append(ipaddress.ip_network(address.exploded))

# O add sem exclusive funciona com tabela existente ou ausente. A exclusão e a
# recriação abaixo pertencem ao MESMO lote atômico, nunca a comandos separados.
lines = [
    "# Generated by render-egress-nftables.sh; do not edit",
    "# Only inet egress_allow is owned by devvps-egress.service",
    "add table inet egress_allow",
    "delete table inet egress_allow",
    "table inet egress_allow {",
    "  set restricted_uids {",
    "    type uid",
    "    elements = { " + ", ".join(map(str, uids)) + " }",
    "  }",
]
for version in (4, 6):
    elements = ", ".join(str(net) for net in ipaddress.collapse_addresses(networks[version]))
    lines += [f"  set allowed_v{version} {{", f"    type ipv{version}_addr", "    flags interval"]
    if elements:
        lines.append(f"    elements = {{ {elements} }}")
    lines.append("  }")
lines += [
    "  chain output {",
    "    type filter hook output priority 100; policy accept;",
    f'    meta skuid @restricted_uids jump agents comment "egress mode: {mode}"',
    "  }",
    "  chain agents {",
    "    ct state established,related counter accept",
    '    oifname "lo" counter accept',
    '    oifname "tailscale0" counter accept',
]
# DNS dos agentes usa o stub local via loopback, nunca porta 53 externa livre.
protocol_rules = set()
for rule in data["always_allow"]:
    protocol, port = rule["protocol"], rule["port"]
    if protocol not in ("tcp", "udp") or not isinstance(port, int) or not 1 <= port <= 65535:
        raise SystemExit(f"Protocolo/porta inválido: {rule}")
    if rule.get("destinations") == "dynamic":
        for version, family in ((4, "ip"), (6, "ip6")):
            protocol_rules.add(f"    {family} daddr @allowed_v{version} {protocol} dport {port} counter accept")
    elif "destinations" in rule:
        raise SystemExit(f"Destino de protocolo não suportado: {rule}")
    else:
        protocol_rules.add(f"    {protocol} dport {port} counter accept")
lines += sorted(protocol_rules)
if policy.get("log_dropped", False):
    lines.append(f'    limit rate 5/second burst 10 packets log prefix "egress-{mode}: "')
verdict = "drop" if mode == "enforce" else "accept"
lines += [f'    counter {verdict} comment "egress unmatched: {mode}"', "  }", "}"]

out_path = Path(out_path)
out_path.parent.mkdir(parents=True, exist_ok=True)
fd, candidate = tempfile.mkstemp(prefix=f".{out_path.name}.", suffix=".nft", dir=out_path.parent)
try:
    with os.fdopen(fd, "w") as stream:
        stream.write("\n".join(lines) + "\n")
        stream.flush()
        os.fsync(stream.fileno())
    os.chmod(candidate, 0o640)
    subprocess.run(["nft", "--check", "--file", candidate], check=True)
    if action == "--apply":
        subprocess.run(["nft", "--file", candidate], check=True)
    os.replace(candidate, out_path)
finally:
    if os.path.exists(candidate):
        os.unlink(candidate)
print(f"egress_mode={mode}; restricted_uids={','.join(map(str, uids))}; applied={action == '--apply'}; output={out_path}")
PY
